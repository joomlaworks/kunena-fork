 * built on Bootstrap 2 (Joomla 3.x UTD's Hammond, most modern templates). Loading Joomla's own copy would restyle the
 * whole page (body, .container, forms...); this one only styles the forum.
 *
 * Usage: php tests/tools/scope-bootstrap.php <folder with bootstrap.css, bootstrap-responsive.css, bootstrap-extended.css>
 * (e.g. a Joomla 3.x UTD site's media/system/css, or Joomla 3.10's media/jui/css)
