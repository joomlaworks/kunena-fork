$source = isset($argv[1]) ? rtrim($argv[1], '/') : '';
$files  = array('bootstrap.css', 'bootstrap-responsive.css', 'bootstrap-extended.css');

foreach ($files as $file) {
    if (!is_file("$source/$file")) {
        fwrite(STDERR, "Missing $source/$file\n");
        exit(1);
    }
}

// Elements Bootstrap's scripts attach to <body>, outside #kunena: left unscoped
$global = '/^\.(tooltip|popover|modal-backdrop)\b/';
$scope  = '#kunena';

/**
 * Scopes the rules of a CSS text (recursing into @media/@supports).
 */
function scopeCss($css, $scope, $global)
{
    $out    = '';
    $length = strlen($css);
    $i      = 0;

    while ($i < $length) {
        $open = strpos($css, '{', $i);

        if ($open === false) {
            break;
        }

        $prelude = trim(substr($css, $i, $open - $i));

        // The matching closing brace
        $depth = 1;
        $j     = $open + 1;

        while ($j < $length && $depth > 0) {
            if ($css[$j] === '{') {
                $depth++;
            } elseif ($css[$j] === '}') {
                $depth--;
            }

            $j++;
        }

        $body = substr($css, $open + 1, $j - $open - 2);
        $i    = $j;

        if ($prelude === '') {
            continue;
        }

        if ($prelude[0] === '@') {
            if (preg_match('/^@(media|supports)\b/i', $prelude)) {
                $out .= $prelude . " {\n" . scopeCss($body, $scope, $global) . "}\n";
            } else {
                // @font-face, @keyframes...: unchanged
                $out .= $prelude . ' {' . $body . "}\n";
            }

            continue;
        }

        $selectors = array();
        $isBody    = false;

        foreach (explode(',', $prelude) as $selector) {
            $selector = trim($selector);

            if ($selector === '') {
                continue;
            }

            if (preg_match($global, $selector)) {
                $selectors[] = $selector;
            } elseif (preg_match('/^(html|body)\b(.*)$/s', $selector, $m)) {
                // The page's html/body rules apply to the forum's container
                $selectors[] = $scope . $m[2];
                $isBody      = $isBody || $m[1] === 'body' && trim($m[2]) === '';
            } else {
                $selectors[] = $scope . ' ' . $selector;
            }
        }

        if ($isBody) {
            // Not the page's margins, padding and background; the forum keeps the site template's font and colour
            $body = preg_replace('/\s*(?<![-\w])(margin|padding(-left|-right|-top|-bottom)?|background-color|font-family|color)\s*:[^;]*;/', '', $body);

            if (trim($body) === '') {
                continue;
            }
        }

        $out .= implode(",\n", array_unique($selectors)) . " {" . $body . "}\n";
    }

    return $out;
}

$result = "/*!\n * Bootstrap v2.3.2 (Copyright 2012 Twitter, Inc; Apache License v2.0), as shipped by Joomla 3, scoped to #kunena.\n"
    . " * Generated by tests/tools/scope-bootstrap.php - don't edit by hand.\n */\n";

foreach ($files as $file) {
    $css = file_get_contents("$source/$file");
    // Comments out (the licence is restated above)
    $css     = preg_replace('#/\*.*?\*/#s', '', $css);
    $result .= "\n/* $file */\n" . scopeCss($css, $scope, $global);
}

$target = dirname(__DIR__, 2) . '/media/kunena/core/css/bootstrap.kunena.css';
file_put_contents($target, $result);
echo "Wrote $target (" . strlen($result) . " bytes)\n";
